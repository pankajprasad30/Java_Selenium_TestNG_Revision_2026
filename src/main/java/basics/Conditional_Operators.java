package basics;

public class Conditional_Operators
{
    // Conditional Operators [>,<,>=,<=,!=,==] (21/02/2026)
    // Arithmetic Operators [+,-,/,*,%]
    public static void main(String[] args)
    {
        int a=10; int b=30;
        if (a>b)
        {
            System.out.println("True");
        }
        else
        {
            System.out.println("False");
        }
        if (a<=b)
        {
            System.out.println("True");
        }
        else
        {
            System.out.println("False");
        }
        if (a!=b)
        {
            System.out.println("True");
        }
        else
        {
            System.out.println("False");
        }
        if (a==b)
        {
            System.out.println("True");
        }
        else {
            System.out.println("False");
        }

    }

}
